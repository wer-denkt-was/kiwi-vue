import { errorMessage } from '@/utils/error'
import { ApiError } from '@/api'

/** Service for handling errors by transforming and displaying error messages */
export interface ApiErrorHandler {
  /** Transform and handle an error by side effect */
  handle(error: unknown): void

  /**
   * Catch errors if the given operation is rejected, handle the resulting error by side effect,
   * and return the rejected promise
   */
  catch<T>(operation: Promise<T>): Promise<T>

  /** Transform an error and return a formatted error message */
  format(error: unknown): string

  /**
   * Wrap an API service such that all promises returned from service methods are handled by this error handler
   * @example ```js
   * class ExampleService extends basicCrudService('Example') { ... }
   * const errorHandler = useApiErrorHandler() // Inject ApiErrorHandler
   * const rawService = useApiService(ExampleService) // Errors unhandled
   * const handledService = errorHandler.wrapService(rawService) // Errors handled by Proxy
   * ```
   * @see {useApiErrorHandler}
   * @see {useApiService}
   */
  wrapService<S extends object>(service: S): S
}

/** Detailed information about an error, generated by an {@link ApiErrorTransformer} */
export interface ApiErrorDetails {
  readonly error: unknown
  readonly rawMessage: string
  readonly formattedMessage: string
  /**
   * Details of nested errors, e.g. one per invalid field of an `entity-body-invalid` error.
   * @see ApiError.errors
   */
  readonly causes?: ReadonlyArray<ApiErrorDetails>
}

/** Provided interface for functions accepting transformed {@link ApiErrorDetails} from an {@link ApiErrorHandler} */
export interface ApiErrorConsumer {
  (error: ApiErrorDetails): void
}

/** Standard error consumer, logging the given error using {@link Console.error} */
export const consoleErrorConsumer: ApiErrorConsumer = error => console.error('Error:', error)

/** Provided interface for functions transforming an unknown error object into {@link ApiErrorDetails} */
export interface ApiErrorTransformer {
  (error: unknown): ApiErrorDetails
}

interface ApiErrorHandlerOptions {
  transform: ApiErrorTransformer
  consumers: ReadonlyArray<ApiErrorConsumer>
  inherit?: boolean
}

const apiErrorHandlerKey = Symbol('error-handler') as InjectionKey<ApiErrorHandler>

/** Create and provide an {@link ApiErrorHandler} to be used in child components. */
export function provideApiErrorHandler(options: ApiErrorHandlerOptions) {
  const parent = options.inherit ? inject(apiErrorHandlerKey, null) : null
  const handler = createApiErrorHandler(options.transform, options.consumers, parent)
  provide(apiErrorHandlerKey, handler)
}

/** Inject the currently available {@link ApiErrorHandler}, or a fallback implementation if none was provided. */
export function useApiErrorHandler(): ApiErrorHandler {
  return inject(apiErrorHandlerKey, fallbackApiErrorHandler)
}

/**
 * Create an {@link ApiErrorTransformer} from a function formatting {@link ApiError}s,
 * which returns `undefined` if no message is available for an error.
 * - Nested errors of an {@link ApiError} (see {@link ApiError.errors}) are transformed into
 *   {@link ApiErrorDetails.causes}. If no message is available for an error with nested errors, its formatted message
 *   consists of the formatted messages of the nested errors, one per line.
 * - Other errors are formatted using their message, see {@link errorMessage}.
 */
export function apiErrorTransformer(formatApiError: (error: ApiError) => undefined | string): ApiErrorTransformer {
  const transform: ApiErrorTransformer = error => {
    const rawMessage = errorMessage(error)
    if (!(error instanceof ApiError)) {
      return { error, rawMessage, formattedMessage: rawMessage }
    }

    const causes = error.errors.map(transform)
    const formattedMessage =
      formatApiError(error) ?? (causes.length > 0 ? causes.map(cause => cause.formattedMessage).join('\n') : rawMessage)
    return causes.length > 0 ? { error, rawMessage, formattedMessage, causes } : { error, rawMessage, formattedMessage }
  }
  return transform
}

/** Simple error transformer, extracting a string from an error and using it as a message */
export const simpleApiErrorTransformer: ApiErrorTransformer = apiErrorTransformer(() => undefined)

const fallbackApiErrorHandler = createApiErrorHandler(simpleApiErrorTransformer, [
  () => console.warn('Warning: No ApiErrorHandler installed, please use provideApiErrorHandler'),
  consoleErrorConsumer,
])

type HandleErrorFn = (error: unknown) => void
type CatchErrorFn = (error: unknown) => never

function createApiErrorHandler(
  transformer: ApiErrorTransformer,
  consumers: ReadonlyArray<ApiErrorConsumer>,
  parentHandler?: null | ApiErrorHandler,
): ApiErrorHandler {
  const handleFn: HandleErrorFn = error => {
    const details = transformer(error)
    consumers.forEach(consumer => consumer(details))
    parentHandler?.handle(error)
  }
  const catchFn: CatchErrorFn = error => {
    handleFn(error)
    throw error
  }
  return {
    handle: handleFn,
    format: error => transformer(error).formattedMessage,
    catch: operation => operation.catch(catchFn),
    wrapService: service => new Proxy(service, createErrorHandlerProxy(catchFn)),
  }
}

interface CachedWrapperFn {
  // eslint-disable-next-line @typescript-eslint/no-unsafe-function-type
  readonly original: Function
  // eslint-disable-next-line @typescript-eslint/no-unsafe-function-type
  readonly wrapped: Function
}

function createErrorHandlerProxy<S extends object>(catchError: CatchErrorFn): ProxyHandler<S> {
  const wrappedFnCache = new Map<PropertyKey, CachedWrapperFn>()

  return {
    // Wrap functions of service with an error-handling function
    get(target: S, property: PropertyKey): unknown {
      // Look up original value from target, return as-is unless property value is a function
      const original: unknown = target[property as keyof S]
      if (typeof original !== 'function') {
        return original
      }

      // Reuse cached wrapped functions if original function is identical
      const cached = wrappedFnCache.get(property)
      if (cached && cached.original === original) {
        return cached.wrapped
      }

      // Create new wrapped functions, handling errors of Promise values returned by the original function
      const wrapped = (...args: readonly unknown[]) => {
        // Invoke original function, pass through function args, and handle Promise return values
        const returnValue = original.call(target, ...args)
        if (!(returnValue instanceof Promise)) {
          return returnValue
        }
        // Apply error handler to return value of original function
        return returnValue.catch(catchError)
      }

      wrappedFnCache.set(property, { original, wrapped })
      return wrapped
    },
  }
}
